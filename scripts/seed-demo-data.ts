/** `YYYY-MM-DD` in a fixed offset-free way, so a run is reproducible. */
function localDate(date: Date): string {
  const year = date.getFullYear()
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return `${year}-${month}-${day}`
}

/**
 * Round half away from zero, once per line.
 *
 * Copied from `packages/shared/src/types/money.ts` deliberately: the invoice arithmetic
 * below has to agree with what the service would compute, or the seeded totals would not
 * match the seeded line items. A seeder that rounds differently from the product is worse
 * than one that does not compute totals at all.
 */
function roundMinor(value: number): number {
  return value < 0 ? -Math.round(-value) : Math.round(value)
}

